const CONTEXT_TEMPLATES = {
  work: ['Созвон в 15:00, не забудь', 'Отчёт готов?', 'Клиент доволен!', 'Обсудим на планёрке'],
  personal: ['Слушай, а помнишь...', 'Кстати, я тут подумал', 'Может, сходим?', 'Как ты?'],
  support: ['Готов помочь!', 'Опишите задачу подробнее', 'Всё сделано ✅', 'Что-то ещё?']
};

export class BotSimulator {
  constructor() {
    this.typing = new Set();
    bus.on('message:sent', ({ chatId }) => this._maybeRespond(chatId));
  }

  async _maybeRespond(chatId) {
    if (this.typing.has(chatId)) return;
    const chat = store.state.chats.find((c) => c.id === chatId);
    if (!chat) return;
    if (chat.type === 'saved' || chat.type === 'channel') return;
    if (!chat.id.startsWith('bot_') && chat.type !== 'group' && chat.type !== 'work') return;

    const messages = store.state.messages[chatId] || [];
    const lastMsg = messages[messages.length - 1];
    if (!lastMsg || lastMsg.authorId !== store.state.user.id) return;

    // Определяем автора ответа
    let author;
    if (chat.type === 'group' || chat.type === 'channel') {
      const others = (chat.participants || []).filter((p) => p.id !== store.state.user.id);
      author = pick(others);
    } else {
      author = { id: chat.id, name: chat.title };
    }
    if (!author) return;

    // Задержка перед "печатает"
    const baseDelay = rand(600, 1800);
    await sleep(baseDelay);

    // Выбираем ответ
    const reply = this._generateReply(lastMsg.text, chat, messages.slice(-5));

    // "Печатает..." — на длину ответа
    this.typing.add(chatId);
    bus.emit('bot:typing', { chatId, authorName: author.name, isTyping: true });

    const typingTime = Math.min(3000, 400 + reply.length * rand(40, 80));
    await sleep(typingTime);

    bus.emit('bot:typing', { chatId, authorName: author.name, isTyping: false });
    this.typing.delete(chatId);

    // Отправляем сообщение
    const msg = createMessage({
      chatId,
      authorId: author.id,
      text: reply,
      status: 'delivered'
    });

    const list = store.state.messages[chatId];
    list.push(msg);
    chat.updatedAt = Date.now();
    if (chatId !== store.state.activeChatId) chat.unread = (chat.unread || 0) + 1;

    bus.emit('messages:append', { chatId, message: msg });
    bus.emit('chats:update');
    bus.emit('bot:replied', { chatId, message: msg });

    // Иногда ставит реакцию на последнее сообщение пользователя
    if (Math.random() < 0.18) {
      setTimeout(() => {
        lastMsg.reactions = lastMsg.reactions || {};
        const emoji = pick(['❤️', '👍', '😂', '🔥']);
        lastMsg.reactions[emoji] = lastMsg.reactions[emoji] || [];
        if (!lastMsg.reactions[emoji].includes(author.id)) lastMsg.reactions[emoji].push(author.id);
        bus.emit('messages:update', { chatId, message: lastMsg });
      }, rand(800, 2200));
    }
  }

  _generateReply(text, chat, recentContext) {
    const lower = (text || '').toLowerCase().trim();

    // Точное совпадение или включение
    for (const [key, answers] of Object.entries(RESPONSES)) {
      if (lower === key || lower.includes(key)) return pick(answers);
    }

    // Вопросы
    if (lower.endsWith('?')) {
      return pick([
        'Хороший вопрос! Дай подумать...',
        'Ну, наверное да',
        'Не уверен, если честно',
        'А сам как думаешь?',
        'Скажу так: возможно',
        'Думаю, да'
      ]);
    }

    // Контекстные
    const contextPool = chat.type === 'group' ? CONTEXT_TEMPLATES.personal : CONTEXT_TEMPLATES.personal;
    if (Math.random() < 0.35) return pick(contextPool);

    // Fallback
    return pick([
      'Понятно',
      'Интересно',
      'Согласен',
      'Ага',
      'Ок',
      'Хорошо',
      'Спасибо за информацию',
      'Понял тебя',
      'Звучит неплохо',
      'Ладно',
      'Договорились',
      'Ха, ну ты даёшь',
      'Хм, никогда об этом не думал'
    ]);
  }
}
